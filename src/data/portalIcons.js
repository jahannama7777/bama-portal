/**
 * تابع جستجوی هوشمند (هم فارسی، هم انگلیسی)
 */
export function searchIcons(query) {
  if (!query || !query.trim()) return ALL_PORTAL_ICONS;
  
  const q = query.toLowerCase().trim();

  return ALL_PORTAL_ICONS.filter((iconName) => {
    // ۱. تطابق با نام اصلی انگلیسی
    if (iconName.toLowerCase().includes(q)) return true;

    // ۲. تطابق با تگ‌های فارسی دیکشنری
    const tags = PERSIAN_ICON_TAGS[iconName];
    if (tags && tags.some((tag) => tag.toLowerCase().includes(q))) {
      return true;
    }

    return false;
  });
}
