// توابع و مقادیر سیستمی که آیکون نیستند
const EXCLUDED_KEYS = new Set([
  'default',
  'createLucideIcon',
  'LucideIcon',
  'icons'
]);

// استخراج خودکار کل آیکون‌های lucide-react
export const ALL_PORTAL_ICONS = Object.keys(LucideIcons)
  .filter((key) => {
    return (
      !EXCLUDED_KEYS.has(key) &&
      /^[A-Z]/.test(key) &&
      (typeof LucideIcons[key] === 'function' || typeof LucideIcons[key] === 'object')
    );
  })
  .sort();

